# Setup-Machine.ps1
# Setup Second Brain agnostico al ruolo (laptop, office, personal).
# Legge la configurazione da %USERPROFILE%\.jsb-config.json.
#
# Uso (PowerShell Admin):
#   PowerShell -ExecutionPolicy Bypass -File Setup-Machine.ps1

param(
    [string]$ConfigPath = "$env:USERPROFILE\.jsb-config.json",
    [switch]$SkipOllamaPull = $false,
    [switch]$SkipTaskScheduler = $false
)

$ErrorActionPreference = "Stop"

Write-Host "=== Second Brain Machine Setup ===" -ForegroundColor Cyan
Write-Host ""

# === FASE 1: Carica configurazione ===
Write-Host "[1/7] Loading configuration..." -ForegroundColor Yellow

if (-not (Test-Path $ConfigPath)) {
    Write-Host "❌ Config not found: $ConfigPath" -ForegroundColor Red
    Write-Host "   Copy a template from templates/ first:" -ForegroundColor Gray
    Write-Host "   - jsb-config.laptop.json"   -ForegroundColor Gray
    Write-Host "   - jsb-config.office.json"   -ForegroundColor Gray
    Write-Host "   - jsb-config.personal.json" -ForegroundColor Gray
    exit 1
}

$cfg = Get-Content $ConfigPath -Raw | ConvertFrom-Json
Write-Host "✅ Config loaded: machine_id=$($cfg.machine_id), role=$($cfg.role)" -ForegroundColor Green

$VaultPath = $cfg.vault_path
$Role = $cfg.role
$IsElaborator = ($Role -eq "elaborator-fast" -or $Role -eq "elaborator-quality")

Write-Host ""

# === FASE 2: Verifica prerequisiti ===
Write-Host "[2/7] Checking prerequisites..." -ForegroundColor Yellow

# Python è richiesto per tutti i ruoli (anche editor-only può eseguire healthcheck)
$pythonPath = (Get-Command python -ErrorAction SilentlyContinue).Source
if (-not $pythonPath) {
    Write-Host "❌ Python not found in PATH. Install from https://www.python.org" -ForegroundColor Red
    exit 1
}
Write-Host "✅ Python: $pythonPath" -ForegroundColor Green

if ($IsElaborator) {
    $ollamaPath = (Get-Command ollama -ErrorAction SilentlyContinue).Source
    if (-not $ollamaPath) {
        $ollamaPath = "$env:USERPROFILE\AppData\Local\Ollama\ollama.exe"
        if (-not (Test-Path $ollamaPath)) {
            Write-Host "❌ Ollama not found. Required for role=$Role." -ForegroundColor Red
            Write-Host "   Download from https://ollama.ai" -ForegroundColor Gray
            exit 1
        }
    }
    Write-Host "✅ Ollama: $ollamaPath" -ForegroundColor Green
}

Write-Host ""

# === FASE 3: Crea struttura vault ===
Write-Host "[3/7] Creating vault structure at $VaultPath..." -ForegroundColor Yellow

if (-not (Test-Path $VaultPath)) {
    New-Item -ItemType Directory -Path $VaultPath -Force | Out-Null
    Write-Host "  Created: $VaultPath" -ForegroundColor Gray
}

$folders = @(
    "inbox\articles", "inbox\notes", "inbox\documents", "inbox\conversations",
    "inbox\_failed",
    "wiki\concepts", "wiki\learn", "wiki\projects", "wiki\decisions",
    "archive", "_system"
)

foreach ($folder in $folders) {
    $path = Join-Path $VaultPath $folder
    if (-not (Test-Path $path)) {
        New-Item -ItemType Directory -Path $path -Force | Out-Null
        Write-Host "  Created: $folder" -ForegroundColor DarkGray
    }
}

# Skeleton files
$indexFile = Join-Path $VaultPath "wiki\index.md"
if (-not (Test-Path $indexFile)) {
    @"
---
type: index
status: active
created: $(Get-Date -Format 'yyyy-MM-dd')
---

# Second Brain — Index

Folders:
- **concepts/** — Ideas, frameworks, theories
- **learn/** — Learning insights, articles, notes
- **projects/** — Project notes and lessons-learned
- **decisions/** — Decision logs and ADRs

Generated by Second Brain system.
"@ | Out-File $indexFile -Encoding UTF8
    Write-Host "  Created: wiki\index.md" -ForegroundColor DarkGray
}

$logFile = Join-Path $VaultPath "_system\ingest-log.md"
if (-not (Test-Path $logFile)) {
    @"
---
status: log
created: $(Get-Date -Format 'yyyy-MM-dd')
---

# Ingest Log

Automated processing history. New entries appended at the bottom.
"@ | Out-File $logFile -Encoding UTF8
    Write-Host "  Created: _system\ingest-log.md" -ForegroundColor DarkGray
}

Write-Host "✅ Vault structure ready" -ForegroundColor Green
Write-Host ""

# === FASE 4: Python dependencies ===
Write-Host "[4/7] Installing Python dependencies..." -ForegroundColor Yellow

$deps = @("requests", "pyyaml")
foreach ($dep in $deps) {
    & python -m pip install $dep --quiet 2>&1 | Out-Null
    Write-Host "  ✓ $dep" -ForegroundColor DarkGray
}
Write-Host "✅ Dependencies installed" -ForegroundColor Green
Write-Host ""

# === FASE 5: Copia script Python ===
Write-Host "[5/7] Deploying Python scripts..." -ForegroundColor Yellow

$scriptDest = Join-Path $VaultPath "_system"
$scriptSource = Join-Path $PSScriptRoot "..\python"

# Se eseguito dal repo, scripts sono in scripts/python/
# Se distribuiti separatamente, l'utente li deve mettere nella stessa cartella
if (-not (Test-Path $scriptSource)) {
    $scriptSource = $PSScriptRoot
}

$pyFiles = @("jsb_core.py", "watchdog.py", "ingest.py", "healthcheck.py")
foreach ($py in $pyFiles) {
    $src = Join-Path $scriptSource $py
    $dst = Join-Path $scriptDest $py
    if (Test-Path $src) {
        Copy-Item $src $dst -Force
        Write-Host "  ✓ $py → $scriptDest" -ForegroundColor DarkGray
    } else {
        Write-Host "  ⚠ $py not found in $scriptSource" -ForegroundColor Yellow
    }
}

Write-Host "✅ Python scripts deployed" -ForegroundColor Green
Write-Host ""

# === FASE 6: Pull modelli Ollama (solo elaborator) ===
if ($IsElaborator -and -not $SkipOllamaPull) {
    Write-Host "[6/7] Pulling Ollama models..." -ForegroundColor Yellow
    $modelDefault = $cfg.ollama.model_default
    $modelQuality = $cfg.ollama.model_quality

    if ($modelDefault) {
        Write-Host "  Pulling $modelDefault (default)..." -ForegroundColor Gray
        & ollama pull $modelDefault
    }
    if ($modelQuality -and $modelQuality -ne $modelDefault) {
        Write-Host "  Pulling $modelQuality (quality)..." -ForegroundColor Gray
        & ollama pull $modelQuality
    }
    Write-Host "✅ Models pulled" -ForegroundColor Green
} else {
    Write-Host "[6/7] Skipping Ollama models (role=$Role or -SkipOllamaPull)" -ForegroundColor DarkGray
}

Write-Host ""

# === FASE 7: Task Scheduler (solo elaborator) ===
if ($IsElaborator -and -not $SkipTaskScheduler) {
    Write-Host "[7/7] Registering Task Scheduler..." -ForegroundColor Yellow

    $watchdogPath = Join-Path $VaultPath "_system\watchdog.py"
    $taskName = "SecondBrain-Watchdog"

    try {
        Unregister-ScheduledTask -TaskName $taskName -Confirm:$false -ErrorAction SilentlyContinue

        $trigger = New-ScheduledTaskTrigger -At 00:00 -Daily
        $action = New-ScheduledTaskAction -Execute "python" -Argument "`"$watchdogPath`""
        $settings = New-ScheduledTaskSettingsSet -AllowStartIfOnBatteries -DontStopIfGoingOnBatteries

        Register-ScheduledTask -TaskName $taskName -Trigger $trigger -Action $action -Settings $settings -Force | Out-Null
        Write-Host "✅ Task Scheduler: $taskName at 00:00 daily" -ForegroundColor Green
    } catch {
        Write-Host "⚠ Could not register Task Scheduler: $_" -ForegroundColor Yellow
        Write-Host "   Run manually as Admin if needed." -ForegroundColor Gray
    }
} else {
    Write-Host "[7/7] Skipping Task Scheduler (role=$Role or -SkipTaskScheduler)" -ForegroundColor DarkGray
}

Write-Host ""

# === Riepilogo ===
Write-Host "============================================" -ForegroundColor Cyan
Write-Host "✅ SETUP COMPLETE" -ForegroundColor Green
Write-Host "============================================" -ForegroundColor Cyan
Write-Host ""
Write-Host "Machine: $($cfg.machine_id) · Role: $Role" -ForegroundColor White
Write-Host ""
Write-Host "Next steps:" -ForegroundColor Yellow

if ($IsElaborator) {
    Write-Host "  1. Test Ollama:    ollama list" -ForegroundColor Gray
    Write-Host "  2. Test watchdog:  python `"$VaultPath\_system\watchdog.py`"" -ForegroundColor Gray
    Write-Host "  3. Healthcheck:    python `"$VaultPath\_system\healthcheck.py`"" -ForegroundColor Gray
}
if ($Role -eq "editor-only") {
    Write-Host "  1. Configure Obsidian + Remotely Save (S3)" -ForegroundColor Gray
    Write-Host "  2. Open vault in Obsidian: $VaultPath" -ForegroundColor Gray
}
if ($cfg.machine_id -eq "laptop-xps15") {
    Write-Host "  4. Enable WoL in BIOS, register MAC on Office PC" -ForegroundColor Gray
    Write-Host "  5. Office PC needs your IP: $(Get-NetIPAddress | Where-Object {$_.AddressFamily -eq 'IPv4' -and $_.PrefixOrigin -eq 'Dhcp'} | Select-Object -ExpandProperty IPAddress -First 1)" -ForegroundColor Gray
}

Write-Host ""
